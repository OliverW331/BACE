def parse_report_filename(path: Path) -> ReportMeta | None:
    match = REPORT_FILENAME_RE.match(path.name)
    if not match:
        return None
    report_token = match.group("report_type").upper()
    return ReportMeta(
        company_id=match.group("company_id"),
        source_year=int(match.group("year")),
        document_type=REPORT_TYPE_MAP[report_token],
        source_file=path.name,
        pdf_path=path,
        inventory_source="filename",
    )


def choose_column(columns: Iterable[str], candidates: list[str]) -> str | None:
    lowered = {column.lower(): column for column in columns}
    for candidate in candidates:
        if candidate.lower() in lowered:
            return lowered[candidate.lower()]
    return None


def normalize_document_type(value: Any, source_file: str | None = None) -> str | None:
    text = clean_text(value).lower()
    text = re.sub(r"[^a-z0-9]+", "_", text).strip("_")
    if text in REPORT_TYPE_MAP:
        return REPORT_TYPE_MAP[text]
    if text.upper() in REPORT_TYPE_MAP:
        return REPORT_TYPE_MAP[text.upper()]
    if source_file:
        parsed = parse_report_filename(Path(source_file))
        if parsed:
            return parsed.document_type
    return None


def load_report_inventory(
    inventory_path: Path,
    reports_dir: Path,
    companies: dict[str, CompanyMeta],
    source_years: list[int] | None,
    include_unlisted_pdfs: bool,
    stats: PdfStats,
) -> list[ReportMeta]:
    records: dict[tuple[str, int, str, str], ReportMeta] = {}

    if inventory_path.exists():
        df = pd.read_csv(inventory_path, low_memory=False)
        company_col = choose_column(df.columns, ["company_id", "firm", "firm_id", "company"])
        year_col = choose_column(df.columns, ["source_year", "year", "reporting_year", "fiscal_year"])
        file_col = choose_column(
            df.columns,
            ["source_file", "filename", "file_name", "pdf_file", "report_file", "path", "pdf_path", "file"],
        )
        type_col = choose_column(df.columns, ["document_type", "report_type", "type", "report_category"])
        title_col = choose_column(df.columns, ["document_title", "title", "report_title"])

        if file_col is None:
            warn_check(
                "report_inventory_no_file_column",
                "falling back to filename parsing because report inventory has no recognized PDF file column",
            )
        else:
            for row in df.to_dict(orient="records"):
                source_file = clean_text(row.get(file_col))
                if not source_file.lower().endswith(".pdf"):
                    continue
                filename = Path(source_file).name
                fallback = parse_report_filename(Path(filename))

                company_id = clean_text(row.get(company_col)) if company_col else ""
                if not company_id and fallback:
                    company_id = fallback.company_id
                if not company_id:
                    stats.unparseable_pdf_files += 1
                    stats.warnings.append({"stage": "inventory", "source_file": filename, "warning": "missing_company_id"})
                    continue

                year_value = row.get(year_col) if year_col else None
                source_year: int | None = None
                try:
                    if clean_text(year_value):
                        source_year = int(float(clean_text(year_value)))
                except ValueError:
                    source_year = None
                if source_year is None and fallback:
                    source_year = fallback.source_year
                if source_year is None:
                    stats.unparseable_pdf_files += 1
                    stats.warnings.append({"stage": "inventory", "source_file": filename, "warning": "missing_source_year"})
                    continue

                document_type = normalize_document_type(row.get(type_col) if type_col else None, filename)
                if document_type is None and fallback:
                    document_type = fallback.document_type
                if document_type is None:
                    stats.unparseable_pdf_files += 1
                    stats.warnings.append({"stage": "inventory", "source_file": filename, "warning": "missing_document_type"})
                    continue

                pdf_path = Path(source_file)
                if not pdf_path.is_absolute():
                    pdf_path = reports_dir / filename

                document_title = clean_text(row.get(title_col)) if title_col else None
                meta = ReportMeta(
                    company_id=company_id,
                    source_year=int(source_year),
                    document_type=document_type,
                    document_title=document_title or None,
                    source_file=filename,
                    pdf_path=pdf_path,
                    inventory_source=str(inventory_path),
                )
                records[(meta.company_id, meta.source_year, meta.document_type, meta.source_file)] = meta

    if include_unlisted_pdfs or not records:
        for pdf_path in sorted(reports_dir.glob("*.pdf")):
            parsed = parse_report_filename(pdf_path)
            if parsed is None:
                stats.unparseable_pdf_files += 1
                stats.warnings.append({"stage": "inventory", "source_file": pdf_path.name, "warning": "unparseable_filename"})
                continue
            records.setdefault((parsed.company_id, parsed.source_year, parsed.document_type, parsed.source_file), parsed)

    stats.pdfs_seen = len(records)
    selected: list[ReportMeta] = []
    selected_company_ids = set(companies.keys())
    source_year_set = set(source_years) if source_years is not None else None

    for meta in sorted(records.values(), key=lambda item: (item.company_id, item.source_year, item.document_type, item.source_file)):
        if meta.company_id not in selected_company_ids:
            continue
        if source_year_set is not None and meta.source_year not in source_year_set:
            continue
        if not meta.pdf_path.exists():
            stats.missing_pdf_files += 1
            stats.warnings.append(
                {
                    "stage": "inventory",
                    "company_id": meta.company_id,
                    "source_file": meta.source_file,
                    "warning": "missing_pdf_file",
                    "expected_path": str(meta.pdf_path),
                }
            )
            continue
        selected.append(meta)

    stats.pdfs_selected = len(selected)
    pass_check(
        "phase_2_report_inventory",
        f"{stats.pdfs_selected:,} PDF reports selected from {stats.pdfs_seen:,} inventory candidates",
    )
    return selected


def clean_extracted_text(text: str) -> tuple[str, list[str]]:
    warnings: list[str] = []
    original = text or ""
    if "\u00ad" in original:
        original = original.replace("\u00ad", "")
        warnings.append("soft_hyphen_removed")
    repaired = re.sub(r"(?<=\w)-\s*\n\s*(?=\w)", "", original)
    if repaired != original:
        warnings.append("hyphenation_repaired")
    repaired = repaired.replace("\r", "\n")
    # Keep block-level text as one paragraph; collapse line breaks inside block.
    repaired = re.sub(r"[ \t]+", " ", repaired)
    repaired = re.sub(r"\s*\n\s*", " ", repaired)
    cleaned = re.sub(r"\s+", " ", repaired).strip()
    return cleaned, warnings


def word_count(text: str) -> int:
    return len(re.findall(r"\b\S+\b", text))


def approximate_token_count(text: str) -> int:
    # Deterministic lightweight approximation. Avoids tokenizer dependency.
    return max(1, math.ceil(len(text) / 4)) if text else 0


def looks_like_table_text(text: str) -> bool:
    if not text:
        return False
    digit_ratio = sum(ch.isdigit() for ch in text) / max(len(text), 1)
    has_many_numbers = len(re.findall(r"\d+(?:[,.]\d+)*", text)) >= 4
    has_separators = "|" in text or "\t" in text or bool(re.search(r"\s{3,}", text))
    return digit_ratio > 0.18 and (has_many_numbers or has_separators)


def split_long_text(text: str, max_words: int) -> list[str]:
    sentences = re.split(r"(?<=[.!?])\s+", text)
    chunks: list[str] = []
    current: list[str] = []
    current_words = 0
    for sentence in sentences:
        sentence = clean_text(sentence)
        if not sentence:
            continue
        sentence_words = word_count(sentence)
        if current and current_words + sentence_words > max_words:
            chunks.append(" ".join(current).strip())
            current = [sentence]
            current_words = sentence_words
        else:
            current.append(sentence)
            current_words += sentence_words
    if current:
        chunks.append(" ".join(current).strip())
    if len(chunks) == 1 and word_count(chunks[0]) > max_words * 1.5:
        # Last-resort deterministic split by words.
        words = chunks[0].split()
        chunks = [" ".join(words[index:index + max_words]) for index in range(0, len(words), max_words)]
    return chunks


def extract_pdf_text_blocks(pdf_path: Path, max_pages: int | None) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    if fitz is None:
        fail("PyMuPDF is not available.")

    summary: dict[str, Any] = {
        "pages_total": 0,
        "pages_processed": 0,
        "warnings": [],
        "errors": [],
    }
    blocks: list[dict[str, Any]] = []

    try:
        document = fitz.open(pdf_path)  # type: ignore[union-attr]
    except Exception as exc:  # noqa: BLE001
        summary["errors"].append({"stage": "text_extraction", "warning": "parser_error", "error": str(exc)})
        return blocks, summary

    with document:
        page_count = len(document)
        summary["pages_total"] = page_count
        limit = min(page_count, max_pages) if max_pages is not None else page_count
        for page_index in range(limit):
            page_number = page_index + 1
            try:
                page = document[page_index]
                raw_blocks = page.get_text("blocks", sort=True)  # type: ignore[attr-defined]
                summary["pages_processed"] += 1
                if not raw_blocks:
                    summary["warnings"].append({"stage": "text_extraction", "page": page_number, "warning": "empty_extracted_text"})
                    continue
                page_block_count = 0
                for block in raw_blocks:
                    if len(block) < 5:
                        continue
                    raw_text = str(block[4])
                    cleaned, cleaning_warnings = clean_extracted_text(raw_text)
                    if not cleaned:
                        continue
                    blocks.append(
                        {
                            "page_number": page_number,
                            "block_index": page_block_count,
                            "raw_text": raw_text,
                            "cleaned_text": cleaned,
                            "processing_warnings": cleaning_warnings,
                        }
                    )
                    page_block_count += 1
                if page_block_count == 0:
                    summary["warnings"].append({"stage": "text_extraction", "page": page_number, "warning": "empty_extracted_text"})
            except Exception as exc:  # noqa: BLE001
                summary["errors"].append(
                    {"stage": "text_extraction", "page": page_number, "warning": "parser_error", "error": str(exc)}
                )
    return blocks, summary


def make_narrative_chunks(
    blocks: list[dict[str, Any]],
    *,
    min_words: int,
    max_words: int,
    min_chars: int,
    include_short: bool,
) -> list[dict[str, Any]]:
    chunks: list[dict[str, Any]] = []
    current_texts: list[str] = []
    current_pages: list[int] = []
    current_warnings: list[str] = []
    current_words = 0

    def flush() -> None:
        nonlocal current_texts, current_pages, current_warnings, current_words
        text = clean_text(" ".join(current_texts))
        if not text:
            current_texts, current_pages, current_warnings, current_words = [], [], [], 0
            return
        warnings = sorted(set(current_warnings))
        if len(text) < min_chars or word_count(text) < min_words:
            warnings.append("very_short_chunk")
            if not include_short and len(text) < min_chars:
                current_texts, current_pages, current_warnings, current_words = [], [], [], 0
                return
        if looks_like_table_text(text):
            warnings.append("possible_table_text")
        if len(set(current_pages)) > 1:
            warnings.append("page_break_joined")
        chunks.append(
            {
                "text": text,
                "page_start": min(current_pages) if current_pages else None,
                "page_end": max(current_pages) if current_pages else None,
                "processing_warnings": sorted(set(warnings)),
            }
        )
        current_texts, current_pages, current_warnings, current_words = [], [], [], 0

    for block in blocks:
        text = clean_text(block["cleaned_text"])
        if not text:
            continue
        text_words = word_count(text)
        if text_words > max_words:
            flush()
            for piece in split_long_text(text, max_words):
                piece_warnings = list(block.get("processing_warnings", []))
                if word_count(piece) < min_words:
                    piece_warnings.append("very_short_chunk")
                if looks_like_table_text(piece):
                    piece_warnings.append("possible_table_text")
                chunks.append(
                    {
                        "text": piece,
                        "page_start": block["page_number"],
                        "page_end": block["page_number"],
                        "processing_warnings": sorted(set(piece_warnings)),
                    }
                )
            continue

        if current_texts and current_words >= min_words and current_words + text_words > max_words:
            flush()

        current_texts.append(text)
        current_pages.append(int(block["page_number"]))
        current_warnings.extend(block.get("processing_warnings", []))
        current_words += text_words

        if current_words >= min_words:
            # Flush at paragraph/block boundary once target minimum is reached.
            flush()

    flush()
    return chunks


