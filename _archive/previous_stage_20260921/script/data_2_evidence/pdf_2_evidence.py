class ProgressTracker:
    """Small dependency-free progress display for long server runs."""

    def __init__(self, total: int, label: str, style: ProgressStyle = "auto") -> None:
        self.total = max(total, 0)
        self.label = label
        self.current = 0
        self.last_line_len = 0
        if style == "auto":
            self.style: ProgressStyle = "bar" if sys.stderr.isatty() else "line"
        else:
            self.style = style
        self.started_at = time.time()

    def update(self, detail: str = "") -> None:
        self.current += 1
        if self.style == "none" or self.total == 0:
            return
        if self.style == "line":
            print(f"[{self.label}] {self.current:,}/{self.total:,} {detail}".rstrip())
            return
        width = 28
        ratio = min(1.0, self.current / self.total) if self.total else 1.0
        done = int(width * ratio)
        bar = "#" * done + "-" * (width - done)
        elapsed = max(time.time() - self.started_at, 0.001)
        rate = self.current / elapsed
        message = (
            f"\r[{self.label}] |{bar}| {self.current:,}/{self.total:,} "
            f"({ratio * 100:5.1f}%) {rate:5.2f} pdf/s {detail}"
        )
        sys.stderr.write(message.ljust(self.last_line_len))
        sys.stderr.flush()
        self.last_line_len = len(message)
        if self.current >= self.total:
            sys.stderr.write("\n")
            sys.stderr.flush()


