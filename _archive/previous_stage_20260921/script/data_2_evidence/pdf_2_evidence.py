def table_id_for(report: ReportMeta, page_number: int, table_index: int) -> str:
    return f"{report.report_token()}_p{page_number:03d}_t{table_index:02d}"


def make_unique_headers(raw_headers: list[Any]) -> tuple[list[str], list[str]]:
    warnings: list[str] = []
    seen: dict[str, int] = defaultdict(int)
    headers: list[str] = []
    for index, value in enumerate(raw_headers):
        header = clean_text(value)
        if not header:
            header = f"unnamed_column_{index}"
            warnings.append("empty_column_header")
        base = header
        seen[base] += 1
        if seen[base] > 1:
            header = f"{base}__{seen[base]}"
            warnings.append("duplicate_column_headers")
        headers.append(header)
    return headers, sorted(set(warnings))


def parse_number(text: str) -> float | int | None:
    value = clean_text(text)
    if not value:
        return None
    # Do not treat accounting parentheses as negative. Remove parentheses but warn elsewhere.
    value = value.strip()
    if value.startswith("(") and value.endswith(")"):
        value = value[1:-1].strip()
    value = value.replace("%", "")
    value = value.replace(",", "")
    value = re.sub(r"\s+", "", value)
    if re.fullmatch(r"[-+]?\d+", value):
        try:
            return int(value)
        except ValueError:
            return None
    if re.fullmatch(r"[-+]?\d*\.\d+", value):
        try:
            return float(value)
        except ValueError:
            return None
    return None


def normalize_cell(header: str, raw_text: Any) -> dict[str, Any]:
    raw = clean_text(raw_text)
    lower = raw.lower()
    header_lower = header.lower()
    warnings: list[str] = []
    normalized_value: Any = None
    value_type = "text"
    unit: str | None = None

    if raw == "" or lower in {"n/a", "na", "not applicable", "not disclosed", "-", "—", "–"}:
        value_type = "missing"
    elif raw.startswith("(") and raw.endswith(")") and parse_number(raw) is not None:
        value_type = "number"
        normalized_value = parse_number(raw)
        warnings.append("parenthesized_number_ambiguous")
    elif "%" in raw and parse_number(raw) is not None:
        value_type = "percent"
        normalized_value = parse_number(raw)
    elif ("year" in header_lower or "date" in header_lower) and re.fullmatch(r"(?:19|20)\d{2}", raw):
        value_type = "year"
        normalized_value = int(raw)
    elif "unit" in header_lower:
        value_type = "unit"
        unit = raw or None
    else:
        number = parse_number(raw)
        if number is not None:
            value_type = "number"
            normalized_value = number
        elif re.fullmatch(r"[A-Za-z0-9/%²³_\-]+", raw) and any(token in lower for token in ["co2", "tco", "mwh", "gwh", "kwh", "ton", "tonne", "eur", "usd", "percent"]):
            value_type = "unit"
            unit = raw

    return {
        "column_header": header,
        "raw_text": raw,
        "normalized_value": normalized_value,
        "value_type": value_type,
        "unit": unit,
        "processing_warnings": sorted(set(warnings)),
    }


def build_row_data(headers: list[str], row: list[Any]) -> tuple[dict[str, str], list[dict[str, Any]], list[str]]:
    warnings: list[str] = []
    adjusted = list(row)
    if len(adjusted) < len(headers):
        adjusted.extend([""] * (len(headers) - len(adjusted)))
        warnings.append("row_cell_count_mismatch")
    elif len(adjusted) > len(headers):
        adjusted = adjusted[: len(headers)]
        warnings.append("row_cell_count_mismatch")

    row_data: dict[str, str] = {}
    cells: list[dict[str, Any]] = []
    for index, header in enumerate(headers):
        raw = clean_text(adjusted[index])
        row_data[header] = raw
        cell = normalize_cell(header, raw)
        cell["column_index"] = index
        # Rebuild to keep stable key order.
        cells.append(
            {
                "column_index": cell["column_index"],
                "column_header": cell["column_header"],
                "raw_text": cell["raw_text"],
                "normalized_value": cell["normalized_value"],
                "value_type": cell["value_type"],
                "unit": cell["unit"],
                "processing_warnings": cell["processing_warnings"],
            }
        )
        warnings.extend(cell["processing_warnings"])
    return row_data, cells, sorted(set(warnings))


def construct_table_retrieval_text(
    company: CompanyMeta,
    report: ReportMeta,
    page_number: int,
    table_title: str | None,
    row_data: dict[str, str],
) -> str:
    source_label = report.document_type.replace("_", " ")
    table_label = f'table "{table_title}"' if table_title else "table"
    pairs = "; ".join(f"{key} = {value}" for key, value in row_data.items() if clean_text(value))
    return (
        f"Company: {company.company_name}. Source: {source_label} {report.source_year}, "
        f"page {page_number}, {table_label}. Table row: {pairs}."
    )


def markdown_for_row(headers: list[str], row_data: dict[str, str]) -> str:
    header_line = "| " + " | ".join(headers) + " |"
    sep_line = "| " + " | ".join("---" for _ in headers) + " |"
    row_line = "| " + " | ".join(row_data.get(header, "") for header in headers) + " |"
    return "\n".join([header_line, sep_line, row_line])


