#!/usr/bin/env python3
"""Build canonical PDF narrative/table evidence cards and update package manifests.

This script converts Corporate Sustainability Tracker PDF reports into deterministic
PDF evidence cards for the W2 transparent evidence-card RAG workflow. It mirrors
the design boundaries of csv_2_evidence.py:

Design boundary:
- Evidence cards are source-centric and permanent.
- Rolling-window membership belongs to package manifests, not to cards.
- No LLM is used during preprocessing.
- PDF narrative retrieval_text is the cleaned extracted PDF chunk.
- PDF table retrieval_text is generated by deterministic template filling from
  the extracted table row structure.

Expected project layout:
    data/
      processed/results/reports_per_company_year.csv
      raw/datasets/companies.csv
      raw/reports_pdf/*.pdf
    evidence/
      canonical/
      builds/

Example:
    python script/data_2_evidence/pdf_2_evidence.py \
      --data-root data \
      --evidence-root evidence \
      --target-years 2018 2019 2020 2021 2022 2023 \
      --csv-window-years 5 \
      --csv-lag-years 0 \
      --pdf-window-years 4 \
      --pdf-lag-years 1 \
      --selected-company-ids config/selected_companies.txt \
      --build-name full_companies_ty2018-2023_csvwin5_pdfwin4_pdflag1 \
      --mode cards-and-packages \
      --overwrite
"""

