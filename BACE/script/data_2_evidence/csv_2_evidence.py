    country: str | None = None
    primary_sics_sector: str | None = None
    metadata_years: list[int] = field(default_factory=list)
    selection_reason: str | None = None
    source_dataset: str | None = None

    def folder_name(self) -> str:
        return f"{self.company_slug}__{self.company_id}"

    def to_json(self) -> dict[str, Any]:
        return {
            "company_id": self.company_id,
            "company_slug": self.company_slug,
            "company_name": self.company_name,
            "isin": self.isin,
            "country": self.country,
            "primary_sics_sector": self.primary_sics_sector,
            "metadata_years": self.metadata_years,
            "selection_reason": self.selection_reason,
            "source_dataset": self.source_dataset,
            "schema_version": "company_metadata_v1",
        }


