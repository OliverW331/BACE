def build_package_manifests(
    args: argparse.Namespace,
    paths: dict[str, Path] | None,
    stats: BuildStats,
    companies: dict[str, CompanyMeta],
) -> None:
    build_name = args.build_name or generated_build_name(args)
    build_root = args.evidence_root / "builds" / build_name

    if build_root.exists():
        if args.overwrite:
            shutil.rmtree(build_root)
        else:
            fail(f"Build folder already exists. Use --overwrite or --build-name: {build_root}")

    build_root.mkdir(parents=True, exist_ok=True)
    write_json(
        build_root / "build_config.json",
        build_config_payload(args, paths, build_name),
        overwrite=True,
    )

    package_rows: list[dict[str, Any]] = []
    missing_reference_count = 0

    for company_id, company in sorted(companies.items(), key=lambda item: (item[1].company_slug, item[0])):
        for target_year in sorted(args.target_years):
            csv_years = rolling_years(target_year, args.csv_window_years, args.csv_lag_years)
            pdf_years = rolling_years(target_year, args.pdf_window_years, args.pdf_lag_years)

            package_metric_ids: list[str] = []
            for source_year in csv_years:
                package_metric_ids.extend(stats.company_year_ids.get(company_id, {}).get(source_year, []))

            for evidence_id in package_metric_ids:
                if evidence_id not in stats.evidence_ids:
                    missing_reference_count += 1

            excluded_pdf_years = []
            if target_year not in pdf_years:
                excluded_pdf_years.append(
                    {
                        "year": target_year,
                        "reason": "current_year_finalized_pdf_excluded_to_reduce_temporal_leakage",
                    }
                )

            package_id = f"{build_name}::{company.company_slug}::{target_year}"
            manifest = {
                "package_id": package_id,
                "build_name": build_name,
                "schema_version": PACKAGE_MANIFEST_SCHEMA_VERSION,
                "company_id": company.company_id,
                "company_slug": company.company_slug,
                "company_name": company.company_name,
                "target_reporting_year": target_year,
                "window_parameters": {
                    "csv_window_years": args.csv_window_years,
                    "csv_lag_years": args.csv_lag_years,
                    "pdf_window_years": args.pdf_window_years,
                    "pdf_lag_years": args.pdf_lag_years,
                },
                "included_source_years": {
                    "csv": csv_years,
                    "pdf": pdf_years,
                },
                "excluded_source_years": {
                    "pdf": excluded_pdf_years,
                },
                "evidence_card_ids": {
                    "csv_metric": package_metric_ids,
                    "pdf_narrative": [],
                    "pdf_table_row": [],
                    "pdf_table_markdown": [],
                },
                "evidence_card_counts": {
                    "csv_metric": len(package_metric_ids),
                    "pdf_narrative": 0,
                    "pdf_table_row": 0,
                    "pdf_table_markdown": 0,
                    "total": len(package_metric_ids),
                },
                "source_status": {
                    "csv_status": "implemented",
                    "pdf_status": "not_implemented",
                },
                "notes": [
                    "CSV cards are canonical source-centric records.",
                    "PDF evidence slots are placeholders for future pdf_narrative_2_evidence.py and pdf_table_2_evidence.py.",
                ],
            }

            manifest_path = (
                build_root
                / "companies"
                / company.folder_name()
                / "manifests"
                / f"package_{target_year}.json"
            )
            write_json(manifest_path, manifest, overwrite=True)

            package_rows.append(
                {
                    "package_id": package_id,
                    "build_name": build_name,
                    "company_id": company.company_id,
                    "company_slug": company.company_slug,
                    "company_name": company.company_name,
                    "target_reporting_year": target_year,
                    "csv_source_years": json.dumps(csv_years),
                    "pdf_source_years": json.dumps(pdf_years),
                    "csv_metric_cards": len(package_metric_ids),
                    "pdf_narrative_cards": 0,
                    "pdf_table_row_cards": 0,
                    "total_cards": len(package_metric_ids),
                    "manifest_path": str(manifest_path),
                }
            )

    if missing_reference_count:
        fail(f"Package manifests contain missing canonical card references: {missing_reference_count:,}")

    package_index = pd.DataFrame(package_rows)
    package_index.to_csv(build_root / "package_index.csv", index=False)

    run_package_integrity_checks(args, build_name, build_root, stats, package_index)
    pass_check(
        "phase_4_package_manifests",
        f"{len(package_rows):,} package manifests written under {build_root}",
    )
    pass_check(
        "phase_5_integrity_checks",
        "package references and rolling-window source years validated",
    )


def run_package_integrity_checks(
    args: argparse.Namespace,
    build_name: str,
    build_root: Path,
    stats: BuildStats,
    package_index: pd.DataFrame,
) -> None:
    if not (build_root / "build_config.json").exists():
        fail("Missing build_config.json.")
    if not (build_root / "package_index.csv").exists():
        fail("Missing package_index.csv.")

    errors: list[str] = []
    manifest_count = 0
    total_manifest_refs = 0

    for manifest_path in build_root.glob("companies/*/manifests/package_*.json"):
        manifest_count += 1
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        target_year = int(manifest["target_reporting_year"])
        expected_csv_years = rolling_years(target_year, args.csv_window_years, args.csv_lag_years)
        expected_pdf_years = rolling_years(target_year, args.pdf_window_years, args.pdf_lag_years)

        if manifest["included_source_years"]["csv"] != expected_csv_years:
            errors.append(f"{manifest_path}: CSV years do not match rolling-window rule.")
        if manifest["included_source_years"]["pdf"] != expected_pdf_years:
            errors.append(f"{manifest_path}: PDF years do not match rolling-window rule.")

        if args.pdf_lag_years > 0 and target_year in manifest["included_source_years"]["pdf"]:
            errors.append(f"{manifest_path}: target year appears in PDF source years despite positive pdf lag.")

        csv_ids = manifest["evidence_card_ids"]["csv_metric"]
        total_manifest_refs += len(csv_ids)
        for evidence_id in csv_ids:
            if evidence_id not in stats.evidence_ids:
                errors.append(f"{manifest_path}: missing evidence_id {evidence_id}")
                continue
            source_year = stats.evidence_id_to_source_year.get(evidence_id)
            if source_year not in expected_csv_years:
                errors.append(
                    f"{manifest_path}: evidence_id {evidence_id} has source year {source_year}, "
                    f"outside {expected_csv_years}"
                )

    expected_manifest_count = len(package_index)
    if manifest_count != expected_manifest_count:
        errors.append(
            f"Manifest count mismatch: found {manifest_count}, package_index has {expected_manifest_count}."
        )

    if errors:
        error_preview = "\n".join(errors[:20])
        fail(f"Package integrity checks failed with {len(errors)} error(s):\n{error_preview}")

    report = {
        "script_version": SCRIPT_VERSION,
        "schema_version": "package_integrity_report_v1",
        "created_at": now_utc_iso(),
        "build_name": build_name,
        "manifest_count": manifest_count,
        "total_manifest_csv_references": total_manifest_refs,
        "target_years": sorted(args.target_years),
        "csv_window_years": args.csv_window_years,
        "csv_lag_years": args.csv_lag_years,
        "pdf_window_years": args.pdf_window_years,
        "pdf_lag_years": args.pdf_lag_years,
        "checks_passed": True,
    }
    write_json(build_root / "package_integrity_report.json", report, overwrite=True)


def main() -> None:
    args = parse_args()
    acceptance_report()
    paths = validate_args_and_paths(args)

    if args.mode in {"cards-and-packages", "cards-only"}:
        stats, companies = build_canonical_cards(args, paths)
    else:
        selected_ids, _ = load_selected_company_table(args.selected_company_ids)
        stats, companies = load_existing_canonical_index(args.evidence_root, selected_ids)

    if args.mode in {"cards-and-packages", "packages-only"}:
        build_package_manifests(args, paths, stats, companies)

    print("\nCompleted successfully.")
    print(f"Mode: {args.mode}")
    print(f"Canonical cards available: {stats.cards_written:,}")
    if args.mode in {"cards-and-packages", "packages-only"}:
        print(f"Build folder: {args.evidence_root / 'builds' / (args.build_name or generated_build_name(args))}")


if __name__ == "__main__":
    main()
