#!/usr/bin/env python3
"""Build canonical CSV metric evidence cards and rolling-window package manifests.

This script converts valid rows from the Corporate Sustainability Tracker
processed CSV into deterministic CSV metric evidence cards. It also creates
parameterized rolling-window package manifests for downstream W2 evidence-card
RAG experiments.

Design boundary:
- Evidence cards are source-centric and permanent.
- Rolling-window membership belongs to package manifests, not to cards.
- No LLM is used during preprocessing.
- CSV retrieval_text is generated by deterministic template filling.

Expected project layout:
    data/
      processed/results/esg_indicators_postprocessed.csv
      raw/datasets/companies.csv
      raw/datasets/indicator_metadata.csv
    evidence/
      canonical/
      builds/

Example:
    python script/data_2_evidence/csv_2_evidence.py \
      --data-root data \
      --evidence-root evidence \
      --target-years 2021 2022 2023 \
      --csv-window-years 3 \
      --csv-lag-years 0 \
      --pdf-window-years 2 \
      --pdf-lag-years 1 \
      --selected-company-ids config/selected_companies.txt \
      --overwrite
"""

